const { chromium } = require(process.env.HEALTH_PLAYWRIGHT_MODULE || 'playwright');
const { mkdirSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const base = process.env.HEALTH_PREVIEW_URL || 'http://127.0.0.1:3000';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.getByRole('heading', { name: 'Buen día, Dr. Mateo' }).waitFor({ timeout: 60000 });
  mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/dashboard-light.png', fullPage: false });
  await page.getByRole('button', { name: 'Tema negro', exact: true }).click();
  await page.screenshot({ path: 'test-results/dashboard-dark.png', fullPage: false });
  await page.getByRole('button', { name: 'Tema navy', exact: true }).click();
  await page.screenshot({ path: 'test-results/dashboard-navy.png', fullPage: false });
  await page.getByRole('button', { name: 'Tema blanco', exact: true }).click();
  await page.getByRole('button', { name: 'Nueva cita', exact: true }).click();
  await page.locator('[data-slot="sheet-content"]').waitFor();
  const panel = await page.locator('[data-slot="sheet-content"]').evaluate(el => ({ side: el.dataset.side, width: el.getBoundingClientRect().width, x: el.getBoundingClientRect().x }));
  const blur = await page.locator('[data-slot="sheet-overlay"]').evaluate(el => getComputedStyle(el).backdropFilter);
  await page.screenshot({ path: 'test-results/sheet-new-appointment.png', fullPage: false });
  const fields = await page.locator('#panel-form').innerText();
  await page.getByRole('button', { name: 'Revisar y continuar', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await page.getByRole('heading', { name: 'Todo listo' }).waitFor();
  await page.getByRole('button', { name: 'Volver a la pantalla' }).click();
  await page.getByRole('link', { name: 'Pacientes', exact: true }).click();
  await page.getByRole('heading', { name: 'Tus pacientes' }).waitFor();
  await page.screenshot({ path: 'test-results/patients.png', fullPage: false });
  await page.goto(base + '/app/atencion/?atencion=e-dental');
  await page.getByRole('heading', { name: 'Un espacio para cuidar' }).waitFor();
  await page.getByLabel('Paciente de la atención').selectOption('p-diego');
  await page.getByRole('tab', { name: 'Gráficos', exact: true }).click();
  await page.screenshot({ path: 'test-results/odontogram.png', fullPage: false });
  await page.getByRole('button', { name: /^Pieza 16/ }).first().click();
  await page.getByRole('button', { name: 'Registrar condición', exact: true }).click();
  await page.locator('[data-slot="sheet-content"]').waitFor();
  await page.getByRole('button', { name: 'Cerrar panel', exact: true }).click();
  await page.locator('.processes').last().evaluate(element => { element.open = true; });
  await page.locator('[data-action="F24_A01"]').last().click();
  await page.getByLabel('Pieza dental').click();
  await page.getByRole('option', { name: 'Pieza 16', exact: true }).click();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.locator('.tooth-button.selected').waitFor();
  const selectedTooth = await page.locator('.tooth-button.selected').innerText();
  if (selectedTooth !== '16') throw new Error('La selección dental no llegó al gráfico.');
  await page.getByLabel('Especialidad de la atención').selectOption('H_CARDIOLOGY');
  await page.locator('.processes').last().evaluate(element => { element.open = true; });
  await page.locator('[data-action="F23_A01"]').last().click();
  await page.locator('[data-slot="sheet-content"]').getByLabel('Vista anatómica').click();
  await page.getByRole('option', { name: /Corazón/ }).click();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.locator('.anatomy-svg').waitFor();
  const selectedAtlas = await page.getByLabel('Vista anatómica').inputValue();
  if (selectedAtlas !== 'heart') throw new Error('La selección del atlas no llegó al gráfico.');
  await page.locator('.processes').last().evaluate(element => { element.open = true; });
  await page.locator('[data-action="F23_A02"]').last().click();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.locator('.atlas-region.selected').waitFor();
  await page.screenshot({ path: 'test-results/cardiology.png', fullPage: false });
  await page.locator('.processes').last().evaluate(element => { element.open = true; });
  await page.locator('[data-action="F23_A05"]').last().click();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.waitForURL(/seleccion=/);
  await page.waitForTimeout(200);
  if (await page.locator('.atlas-region.selected').count()) throw new Error('Deshacer no limpió la selección local.');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await page.getByRole('heading', { name: 'Buen día, Dr. Mateo' }).waitFor();
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  const result = { http: response.status(), panel, blur, fields, selectedTooth, selectedAtlas, graphicUndo: true, mobileOverflow: overflow, errors };
  writeFileSync(resolve('test-results/preview-qa.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
